export const FEATURE_GROUPS = groups.map((group) => ({
  ...group,
  total: group.items.length,
}));

export const FEATURE_CATALOG = groups.flatMap((group) =>
  group.items.map(([id, name]) => ({
    id,
    name,
    group: group.id,
    groupName: group.name,
    status: group.status,
    icon: group.icon,
  }))
);

export function catalogSummary() {
  const byGroup = FEATURE_GROUPS.map((group) => ({
    id: group.id,
    name: group.name,
    icon: group.icon,
    total: group.total,
  }));
  return {
    total: FEATURE_CATALOG.length,
    groups: byGroup.length,
    byGroup,
    newCount: FEATURE_CATALOG.filter((f) => f.status === 'new').length,
  };
}
