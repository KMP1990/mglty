export function instructionFor(task, question, pages) {
  const scope =
    pages.length > 1
      ? `لديك ${pages.length} صفحات (${pages.map((p) => p.number).join('، ')}).`
      : pages.length === 1
        ? `الصفحة ${pages[0].number}.`
        : 'المطلوب من مقتطفات البحث في الكتاب.';
  const base = {
    summary:
      'لخّص فقط: ماذا تقول الصفحة؟ جملتان قصيرتان كحد أقصى. أدرج العدد أو القائمة المهمة إن وجدت. لا شرح، لا أسئلة، لا تبسيط، ولا إعادة لأي فكرة.',
    simple:
      'أعد الخلاصة بجملتين بسيطتين كحد أقصى. لا شرح إضافي ولا مقدمات.',
    ask: `أجب عن سؤال القارئ: «${question}» بجملتين قصيرتين كحد أقصى. إن طلب التبسيط، بسّط الجواب نفسه ولا تزد فقرة شرح.`,
    image: 'اوصف الصورة أو الرسمة بجملة أو جملتين: ما هي وما الذي تعرضه. لا تشرح كيف تُقرأ إلا إذا طُلب.',
    explain:
      'لخّص المحتوى في جملتين فقط. لا تشرح خطوة بخطوة ولا تكرر النقاط.',
  }[task] || 'لخّص المحتوى بجملتين كحد أقصى.';
  return `${scope} ${base}`;
}
