/**
 * تصحيح OCR محلي سريع — يعمل حتى بلا إنترنت.
 * لا يغيّر المعنى؛ فقط المسافات والحروف الملتصقة والأخطاء الشائعة.
 */
const BIDI = /[\u200B-\u200F\u202A-\u202E\u2060-\u2069\uFEFF]/g;

export function repairOcrText(value) {
  let text = String(value || '')
    .normalize('NFKC')
    .replace(BIDI, '')
    .replace(/\r\n?/g, '\n')
    .replace(/\u00A0/g, ' ');

  const fixes = [
    [/لميكن/g, 'لم يكن'],
    [/أنيجعل/g, 'أن يجعل'],
    [/ذكاءومصداقية/g, 'ذكاء ومصداقية'],
    [/وإرياكناء/g, 'وإرباكنا'],
    [/يفهمهاء/g, 'يفهمها'],
    [/خبيرومثقف/g, 'خبير ومثقف'],
    [/المعرفةالحقيقية/g, 'المعرفة الحقيقية'],
    [/منتج ماء على/g, 'منتج ما، على'],
    [/حتىحقيقية/g, 'حتى حقيقية'],
    [/علىال/g, 'على ال'],
    [/إلىال/g, 'إلى ال'],
    [/(^|\s)ه\s+(التفصيل)/gu, '$1هذا $2'],
    [/([\u0621-\u064A])هاء(?=[\s،.!؟:؛]|$)/gu, '$1ها'],
    [/([\u0621-\u064A](?:ة|ات|ون|ين|اء))ال([\u0621-\u064A]{3,})/gu, '$1 ال$2'],
    [/[:؛]\s*؛/g, ':'],
  ];
  for (const [from, to] of fixes) text = text.replace(from, to);

  return text
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/([،؛.!؟:])(?=[^\s\d])/g, '$1 ')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}
